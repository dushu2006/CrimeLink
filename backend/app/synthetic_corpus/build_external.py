# ---------------------------------------------------------------------------

DEFAULT_SEED = 20260902

BACKEND_DIR = Path(__file__).resolve().parents[2]
CORPUS_ROOT = BACKEND_DIR / "CrimeLink_Synthetic_Corpus_v1"

OPERATIONAL_DIR = "operational"
DOCUMENTS_DIR = "documents"
GROUND_TRUTH_DIR = "ground_truth"
METADATA_DIR = "metadata"

N_CASES = 12
PERSONS_PER_CASE = 8
BACKGROUND_PERSONS = 24

# Synthetic name pools — generated combinations, never real people.
FIRST_NAMES = [
    "Aarav", "Ananya", "Arjun", "Bhavna", "Chetan", "Deepika", "Dev", "Divya",
    "Gaurav", "Ishaan", "Kavya", "Lakshmi", "Manoj", "Meera", "Nikhil", "Nisha",
    "Pranav", "Priya", "Rahul", "Rani", "Rohit", "Sanya", "Sanjay", "Sneha",
    "Tanvi", "Vikram", "Yash", "Zoya",
]
LAST_NAMES = [
    "Acharya", "Babu", "Bhat", "Chauhan", "Das", "Goud", "Hegde", "Iyer",
    "Joshi", "Kulkarni", "Mishra", "Nair", "Patil", "Pillai", "Rao", "Reddy",
    "Saxena", "Sharma", "Singh", "Verma", "Yadav",
]

GENDERS = ["M", "F"]
STATES = ["Andhra Pradesh", "Karnataka", "Maharashtra", "Rajasthan", "Telangana"]
CITIES = {
    "Andhra Pradesh": ["Visakhapatnam", "Kurnool", "Vijayawada"],
    "Karnataka": ["Bengaluru", "Mysuru", "Hubballi"],
    "Maharashtra": ["Pune", "Nagpur", "Nashik"],
    "Rajasthan": ["Jaipur", "Kota", "Udaipur"],
    "Telangana": ["Hyderabad", "Warangal", "Nizamabad"],
}

LOCATION_NAMES = [
    "Warehouse", "Petrol Pump", "Bus Stand", "Railway Station", "Market",
    "Industrial Area", "Highway Junction", "Hotel", "Checkpost", "Toll Plaza",
]
