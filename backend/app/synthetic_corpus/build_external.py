"""Regenerate the CrimeLink external synthetic corpus (v2).

The previous corpus was generated by drawing mostly-random rows and leaving
~70% of CDR / transaction / sighting / intel records without a ``case_id``.
That produced exactly the artefact the reviewer flagged: the ingestion
pipeline had no coherent story to attach rows to, so the graph filled up with
dangling "negatives" that meant nothing.

This generator rebuilds the corpus around two explicit populations:

* **Case population** — every event row belongs to a named case and references
  entities (people, phones, vehicles, accounts, locations) that are actually
  members of that case.  Rows carry an explicit ``case_id``.
* **Background population** — a smaller, self-contained social circle of
  people who are *not* members of any case.  Their calls and transfers are
  internally coherent (they phone and pay each other), but they carry no
  ``case_id`` and are the "unrelated" negative class.  The source adapter
  quarantines them with the honest reason ``subject_in_no_case`` — real,
  unrelated people, not garbage.

Everything is deterministic (``random.Random(seed)``) so the corpus can be
rebuilt identically.  Only the standard library is used, so the generator runs
without the application's dependencies.

Run from the backend directory:

    python3 app/synthetic_corpus/build_external.py

The output replaces ``backend/CrimeLink_Synthetic_Corpus_v1``.
"""

